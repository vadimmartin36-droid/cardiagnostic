    private fun normalizeString(input: String): String {
        return input
            .trim()
            .lowercase()
            .replace('ё', 'е')
            .replace('ë', 'e')
            .replace('é', 'e')
            .replace('è', 'e')
            .replace('ê', 'e')
            .replace('š', 's')
            .replace('č', 'c')
            .replace('ž', 'z')
            .replace(" ", "")
            .replace("-", "")
    }

    /**
     * Resolves canonical brand name or finds matching brand key.
     */
    fun findCanonicalBrand(inputBrand: String): String? {
        val trimmed = inputBrand.trim()
        if (trimmed.isEmpty()) return null

        // Direct match
        BRANDS.firstOrNull { it.equals(trimmed, ignoreCase = true) }?.let { return it }

        // Alias lookup
        val lower = trimmed.lowercase()
        BRAND_ALIASES[lower]?.let { return it }

        // Normalized match
        val normInput = normalizeString(trimmed)
        BRANDS.firstOrNull { normalizeString(it) == normInput }?.let { return it }

        // Partial match
        BRANDS.firstOrNull { normalizeString(it).contains(normInput) || normInput.contains(normalizeString(it)) }?.let { return it }

        return null
    }

    /**
     * Retrieves all models for a given brand name (supporting diacritics and aliases).
     */
    fun getModelsForBrand(brandName: String): List<String> {
        val trimmed = brandName.trim()
        if (trimmed.isEmpty()) return emptyList()

        // Exact match in map
        MODELS_BY_BRAND[trimmed]?.let { return it }

        // Canonical brand resolution
        val canonical = findCanonicalBrand(trimmed)
        if (canonical != null) {
            MODELS_BY_BRAND[canonical]?.let { return it }
        }

        // Search in map by normalized key
        val normInput = normalizeString(trimmed)
        for ((key, models) in MODELS_BY_BRAND) {
            if (normalizeString(key) == normInput || normInput.contains(normalizeString(key)) || normalizeString(key).contains(normInput)) {
                return models
            }
        }

        return emptyList()
    }

    /**
     * Filters brands by search query (supports English, Russian, diacritics).
     */
    fun filterBrands(query: String): List<String> {
        val trimmed = query.trim()
        if (trimmed.isEmpty()) return BRANDS

        val normQuery = normalizeString(trimmed)
        val lowerQuery = trimmed.lowercase()

        val matchingCanonicalFromAlias = BRAND_ALIASES.entries
            .filter { it.key.contains(lowerQuery) || lowerQuery.contains(it.key) }
            .map { it.value }
            .toSet()

        return BRANDS.filter { brand ->
            brand.contains(trimmed, ignoreCase = true) ||
            normalizeString(brand).contains(normQuery) ||
            matchingCanonicalFromAlias.contains(brand)
        }
    }

    /**
     * Filters models for a brand by query.
     */
    fun filterModels(brand: String, query: String): List<String> {
        val models = getModelsForBrand(brand)
        val trimmed = query.trim()
        if (trimmed.isEmpty()) return models

        val normQuery = normalizeString(trimmed)
        return models.filter { model ->
            model.contains(trimmed, ignoreCase = true) ||
            normalizeString(model).contains(normQuery)
        }
    }

